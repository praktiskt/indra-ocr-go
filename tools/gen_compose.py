#!/usr/bin/env python3
"""Generate compose_table.go: the spacing-diacritic -> combining-mark map and the
canonical (combining-mark, base) -> precomposed table used by foldSpacingAccents
in pdfium.go.

Run from the repo root:

    python3 tools/gen_compose.py > compose_table.go

The spacing forms are the TeX text-companion glyphs that PDF text layers emit
before/after their base (see pdfium.go). Only canonical decompositions (no
compatibility tag) are used, so composing is exactly Unicode NFC for a single
mark; double-marked letters (Vietnamese) build up by successive composition.
"""
import sys
import unicodedata as ud

# combining mark -> the spacing glyphs a PDF may use for it
SPACING = {
    0x0300: [0x0060, 0x02CB],  # grave
    0x0301: [0x00B4, 0x02CA],  # acute
    0x0302: [0x02C6],          # circumflex
    0x0303: [0x02DC],          # tilde
    0x0304: [0x00AF, 0x02C9],  # macron
    0x0306: [0x02D8],          # breve
    0x0307: [0x02D9],          # dot above
    0x0308: [0x00A8],          # diaeresis
    0x030A: [0x02DA],          # ring above
    0x030B: [0x02DD],          # double acute
    0x030C: [0x02C7],          # caron
    0x0327: [0x00B8],          # cedilla
    0x0328: [0x02DB],          # ogonek
}
MARKS = set(SPACING)

spacing_to_mark = {}
for mark, forms in SPACING.items():
    for sp in forms:
        spacing_to_mark[sp] = mark

compose = {}  # mark -> {base: precomposed}
for cp in range(0x110000):
    ch = chr(cp)
    d = ud.decomposition(ch)
    if not d or d.startswith('<'):
        continue
    parts = d.split()
    if len(parts) != 2:
        continue
    base, mark = int(parts[0], 16), int(parts[1], 16)
    if mark not in MARKS:
        continue
    compose.setdefault(mark, {})[base] = cp

# Some fonts draw an accented i/j as a dotless i/j (U+0131/U+0237) plus the
# accent; those are not canonical compositions, so map them to the dotted base's
# result (Old-Hungarian/Turkish-style fonts; the recognizer's NFC output keeps
# the dotted form).
for mark, bases in compose.items():
    cp = bases.get(0x0069)
    if cp is not None and 0x0131 not in bases:
        bases[0x0131] = cp
    cp = bases.get(0x006A)
    if cp is not None and 0x0237 not in bases:
        bases[0x0237] = cp

out = sys.stdout
out.write("// Code generated by tools/gen_compose.py. DO NOT EDIT.\n")
out.write("//\n")
out.write("// spacingMarks maps a spacing diacritic (the text-companion glyph a PDF\n")
out.write("// text layer emits before or after its base) to the combining mark it is\n")
out.write("// equivalent to. composeMark maps a combining mark + base letter to the\n")
out.write("// precomposed character (canonical composition, i.e. Unicode NFC with a\n")
out.write("// single mark). See foldSpacingAccents in pdfium.go.\n")
out.write("package indra\n\n")

out.write("var spacingMarks = map[rune]rune{\n")
for sp in sorted(spacing_to_mark):
    out.write("\t0x%04X: 0x%04X,\n" % (sp, spacing_to_mark[sp]))
out.write("}\n\n")

out.write("var composeMark = map[rune]map[rune]rune{\n")
for mark in sorted(compose):
    out.write("\t0x%04X: {\n" % mark)
    for base in sorted(compose[mark]):
        out.write("\t\t0x%04X: 0x%04X,\n" % (base, compose[mark][base]))
    out.write("\t},\n")
out.write("}\n")

n = sum(len(v) for v in compose.values())
sys.stderr.write("spacing forms: %d, compose entries: %d\n" % (len(spacing_to_mark), n))
